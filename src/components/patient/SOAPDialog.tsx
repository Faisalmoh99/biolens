const PROGRESS_STEPS = [
  "soap.generating.step1",
  "soap.generating.step2",
  "soap.generating.step3",
  "soap.generating.step4",
  "soap.generating.step5",
] as const;

type SectionKey = "subjective" | "objective" | "assessment" | "plan";
const SECTIONS: { key: SectionKey; letter: string; labelKey: string }[] = [
  { key: "subjective", letter: "S", labelKey: "soap.section.s.label" },
  { key: "objective", letter: "O", labelKey: "soap.section.o.label" },
  { key: "assessment", letter: "A", labelKey: "soap.section.a.label" },
  { key: "plan", letter: "P", labelKey: "soap.section.p.label" },
];

function buildPreFill(triageActions?: string[]): string {
  if (!triageActions || triageActions.length === 0) return "";
  const joined = triageActions
    .map((a) => a.trim().replace(/[.?!]+$/, ""))
    .join(". ");
  return joined + ".";
}

function formatTimestamp(iso: string): string {
  const d = new Date(iso);
  if (Number.isNaN(d.getTime())) return iso;
  return d.toLocaleString(undefined, {
    day: "2-digit",
    month: "short",
    year: "numeric",
    hour: "2-digit",
    minute: "2-digit",
    second: "2-digit",
  });
}

function formatPlainSOAP(patient: Patient, note: SOAPNote): string {
  return [
    "CLINICAL SOAP NOTE",
    "",
    `Patient: ${patient.fullName.en}`,
    `MR #: ${patient.hajjPermitNumber}`,
    `Age/Sex: ${patient.age}yo ${patient.sex}`,
    `Generated: ${formatTimestamp(note.generatedAt)}`,
    "",
    "S — SUBJECTIVE",
    note.subjective,
    "",
    "O — OBJECTIVE",
    note.objective,
    "",
    "A — ASSESSMENT",
    note.assessment,
    "",
    "P — PLAN",
    note.plan,
    "",
    "---",
    "Generated by BioLens AI.",
    "This note was AI-assisted. Reviewing clinician must verify before signing.",
  ].join("\n");
}

export function SOAPDialog({
  patient,
  triageActions,
  open,
  onOpenChange,
}: SOAPDialogProps) {
  const { t } = useTranslation();
  const soapCache = useAppStore((s) => s.soapCache);
  const setSOAPNote = useAppStore((s) => s.setSOAPNote);

  const initialIntervention = useMemo(
    () => buildPreFill(triageActions),
    [triageActions],
  );

  const [intervention, setIntervention] = useState(initialIntervention);
  const [note, setNote] = useState<SOAPNote | null>(null);
  const [loading, setLoading] = useState(false);
  const [progress, setProgress] = useState(0);
  const [stepIdx, setStepIdx] = useState(0);
  const [error, setError] = useState<string | null>(null);
  const [editing, setEditing] = useState<SectionKey | null>(null);
  const [draftValue, setDraftValue] = useState("");
  const [cachedInterventionAtGen, setCachedInterventionAtGen] =
    useState<string>("");
  const [demoMiss, setDemoMiss] = useState(false);

  const textareaRef = useRef<HTMLTextAreaElement>(null);
  const progressTimerRef = useRef<number | null>(null);
  const stepTimerRef = useRef<number | null>(null);

  // Reset form state when dialog opens. Synchronous setState inside the
  // open transition is intentional: we treat dialog open/close as a remount
  // for the form's internal state.
  useEffect(() => {
    if (!open) return;
    const cached = soapCache[patient.id];
    /* eslint-disable react-hooks/set-state-in-effect */
    if (cached) {
      setNote(cached);
      setIntervention(initialIntervention);
      setCachedInterventionAtGen(initialIntervention);
    } else {
      setNote(null);
      setIntervention(initialIntervention);
      setCachedInterventionAtGen("");
    }
    setError(null);
    setDemoMiss(false);
    setEditing(null);
    setProgress(0);
    setStepIdx(0);
    setLoading(false);
    /* eslint-enable react-hooks/set-state-in-effect */
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [open, patient.id]);

  // Cleanup timers on unmount/close
  useEffect(() => {
    return () => {
      if (progressTimerRef.current) window.clearInterval(progressTimerRef.current);
      if (stepTimerRef.current) window.clearInterval(stepTimerRef.current);
    };
  }, []);

  const appendChip = (text: string) => {
    setIntervention((prev) => {
      const sep = prev.length === 0 || prev.endsWith(" ") ? "" : " ";
      return prev + sep + text + " ";
    });
    textareaRef.current?.focus();
  };

  const startProgressAnimation = () => {
    setProgress(0);
    setStepIdx(0);
    const total = 4000;
    const tick = 80;
    const increment = (100 / total) * tick;
    progressTimerRef.current = window.setInterval(() => {
      setProgress((p) => Math.min(95, p + increment));
    }, tick);
    stepTimerRef.current = window.setInterval(() => {
      setStepIdx((i) => Math.min(PROGRESS_STEPS.length - 1, i + 1));
    }, 800);
  };

  const stopProgressAnimation = () => {
    if (progressTimerRef.current) {
      window.clearInterval(progressTimerRef.current);
      progressTimerRef.current = null;
    }
    if (stepTimerRef.current) {
      window.clearInterval(stepTimerRef.current);
      stepTimerRef.current = null;
    }
    setProgress(100);
  };

  const runGenerate = async (force: boolean) => {
    const trimmed = intervention.trim();
    if (!trimmed) return;

    // Demo builds always serve the cached note and never call Gemini.
    if (DEMO_ONLY) {
      const cachedNote = soapCache[patient.id];
      if (cachedNote) setNote(cachedNote);
      else setDemoMiss(true);
      return;
    }

    // Cache hit: same intervention text and a cached note exists
    if (
      !force &&
      soapCache[patient.id] &&
      trimmed === cachedInterventionAtGen.trim()
    ) {
      setNote(soapCache[patient.id]);
      return;
    }

    setLoading(true);
    setError(null);
    setNote(null);
    startProgressAnimation();
    try {
      const result = await generateSOAPNote(patient, trimmed);
      setNote(result);
      setSOAPNote(patient.id, result);
      setCachedInterventionAtGen(trimmed);
    } catch (err) {
      console.error("[SOAP] generation failed", err);
      setError(t("soap.error"));
    } finally {
      stopProgressAnimation();
      setLoading(false);
    }
  };

  const handleEdit = (key: SectionKey) => {
    if (!note) return;
    setEditing(key);
    setDraftValue(note[key]);
  };

  const handleDone = () => {
    if (!note || !editing) return;
    const updated = { ...note, [editing]: draftValue };
    setNote(updated);
    setSOAPNote(patient.id, updated);
    setEditing(null);
  };

  const handleCopy = async () => {
    if (!note) return;
    try {
      await navigator.clipboard.writeText(formatPlainSOAP(patient, note));
      toast.success(t("soap.copied"));
    } catch (err) {
      console.error("[SOAP] clipboard failed", err);
    }
  };

  const handlePrint = () => {
    if (!note) return;
    document.body.setAttribute("data-soap-print", "active");
    window.print();
    window.setTimeout(() => {
      document.body.removeAttribute("data-soap-print");
    }, 100);
  };

  const handleRegenerate = () => {
    void runGenerate(true);
  };

  const stepCaption = t(PROGRESS_STEPS[stepIdx]);
  const interventionEmpty = intervention.trim().length === 0;

  return (
    <Dialog open={open} onOpenChange={onOpenChange}>
      <DialogContent className="max-h-[90vh] max-w-3xl overflow-y-auto border-medical-cyan/30 bg-medical-deep p-0">
        <div data-soap-printable>
          {/* Header */}
          <div className="border-b border-medical-cyan/20 px-6 py-4">
            <DialogTitle className="text-xl font-bold text-medical-glow">
              {t("soap.title")}
            </DialogTitle>
          </div>

          {/* Patient banner */}
          <div className="border-b border-medical-cyan/10 bg-medical-surface/40 px-6 py-3 text-sm text-foreground/80">
            <div className="flex flex-wrap items-center gap-x-3 gap-y-1">
              <span className="font-semibold text-medical-glow">
                {t("soap.patient")}:
              </span>
              <span>{patient.fullName.en}</span>
              <span className="text-foreground/30">·</span>
              <span>MR #{patient.hajjPermitNumber}</span>
              <span className="text-foreground/30">·</span>
              <span>
                {patient.age}yo {patient.sex}
              </span>
            </div>
          </div>

          {/* Intervention input (hidden when printing) */}
          <div className="soap-print-no space-y-3 px-6 py-5">
            <h3 className="text-xs font-semibold uppercase tracking-[0.2em] text-medical-glow">
              {t("soap.interventions")}
            </h3>
            <textarea
              ref={textareaRef}
              value={intervention}
              onChange={(e) => setIntervention(e.target.value)}
              readOnly={DEMO_ONLY}
              placeholder={t("soap.interventions.placeholder")}
              className="min-h-[100px] w-full resize-y rounded-md border border-medical-cyan/30 bg-medical-surface/60 px-3 py-2 text-sm text-foreground placeholder:text-foreground/40 focus:border-medical-cyan/60 focus:outline-none"
              disabled={loading}
            />
            <div className="flex flex-wrap gap-2">
              {QUICK_INTERVENTIONS.map((chip) => (
                <button
                  key={chip.id}
                  type="button"
                  onClick={() => appendChip(chip.text)}
                  disabled={loading || DEMO_ONLY}
                  className="disabled:opacity-50"
                >
                  <Badge
                    variant="outline"
                    className="cursor-pointer border-medical-cyan/40 bg-medical-cyan/5 text-medical-glow transition-all hover:-translate-y-0.5 hover:border-medical-cyan/80 hover:bg-medical-cyan/15"
                  >
                    {t(chip.labelKey)}
                  </Badge>
                </button>
              ))}
            </div>

            {/* Generate button OR progress */}
            <div className="pt-2">
              {loading ? (
                <div className="space-y-2">
                  <Progress value={progress} />
                  <p className="text-sm text-medical-glow/80">{stepCaption}</p>
                </div>
              ) : (
                <Button
                  onClick={() => void runGenerate(false)}
                  disabled={interventionEmpty}
                  className="bg-medical-cyan text-medical-deep hover:bg-medical-glow"
                >
                  {t("soap.generate")}
                </Button>
              )}
              {error && !loading && (
                <p className="mt-2 text-sm text-red-400">{error}</p>
              )}
              {demoMiss && !loading && <DemoNotice className="mt-2" />}
            </div>
          </div>

          {/* SOAP sections */}
          {note && (
            <div className="space-y-4 border-t border-medical-cyan/10 px-6 py-5">
              {SECTIONS.map((sec) => {
                const isEditing = editing === sec.key;
                return (
                  <GlowCard
                    key={sec.key}
                    interactive={false}
                    className="p-4"
                  >
                    <div className="flex items-start gap-4">
                      <div
                        className={cn(
                          "flex h-12 w-12 shrink-0 items-center justify-center rounded-lg border border-medical-cyan/40 bg-medical-cyan/10 text-2xl font-bold text-medical-glow",
                        )}
                      >
                        {sec.letter}
                      </div>
                      <div className="flex-1">
                        <div className="mb-2 flex items-center justify-between">
                          <h4 className="text-xs font-semibold uppercase tracking-[0.2em] text-medical-glow">
                            {sec.letter} — {t(sec.labelKey)}
                          </h4>
                          <div className="soap-print-no">
                            {isEditing ? (
                              <Button
                                size="sm"
                                variant="outline"
                                onClick={handleDone}
                                className="h-7 border-medical-cyan/40 text-medical-glow"
                              >
                                <Check className="h-3 w-3" />
                                {t("soap.done")}
                              </Button>
                            ) : (
                              <Button
                                size="sm"
                                variant="ghost"
                                onClick={() => handleEdit(sec.key)}
                                className="h-7 text-medical-glow/80 hover:bg-medical-cyan/10 hover:text-medical-glow"
                              >
                                <Edit3 className="h-3 w-3" />
                                {t("soap.edit")}
                              </Button>
                            )}
                          </div>
                        </div>
                        {isEditing ? (
                          <textarea
                            value={draftValue}
                            onChange={(e) => setDraftValue(e.target.value)}
                            className="min-h-[120px] w-full resize-y rounded-md border border-medical-cyan/40 bg-medical-surface/60 px-3 py-2 text-sm text-foreground focus:border-medical-cyan/80 focus:outline-none"
                            autoFocus
                          />
                        ) : (
                          <p className="whitespace-pre-wrap text-sm leading-relaxed text-foreground/90">
                            {note[sec.key]}
                          </p>
                        )}
                      </div>
                    </div>
                  </GlowCard>
                );
              })}

              {!DEMO_ONLY && (
              <div className="soap-print-no flex justify-center pt-1">
                <button
                  type="button"
                  onClick={handleRegenerate}
                  className="inline-flex items-center gap-1 text-xs text-medical-glow/70 underline-offset-4 hover:text-medical-glow hover:underline"
                >
                  <RefreshCcw className="h-3 w-3" />
                  {t("soap.regenerate")}
                </button>
              </div>
              )}
            </div>
          )}

          {/* Footer */}
          {note && (
            <div className="border-t border-medical-cyan/10 bg-medical-surface/40 px-6 py-3 text-xs text-foreground/60">
              <p>
                {t("soap.footer.generated")} ·{" "}
                {formatTimestamp(note.generatedAt)}
              </p>
              <p className="mt-1 italic">{t("soap.footer.disclaimer")}</p>
            </div>
          )}
        </div>

        {/* Action footer (not printed) */}
        {note && (
          <div className="soap-print-no flex flex-wrap items-center justify-end gap-2 border-t border-medical-cyan/20 px-6 py-3">
            <Button
              variant="outline"
              size="sm"
              onClick={handleCopy}
              className="border-medical-cyan/40 text-medical-glow hover:bg-medical-cyan/10"
            >
              <ClipboardCopy className="h-4 w-4" />
              {t("soap.copy")}
            </Button>
            <Button
              variant="outline"
              size="sm"
              onClick={handlePrint}
              className="border-medical-cyan/40 text-medical-glow hover:bg-medical-cyan/10"
            >
              <Printer className="h-4 w-4" />
              {t("soap.print")}
            </Button>
            <Button
              variant="ghost"
              size="sm"
              onClick={() => onOpenChange(false)}
            >
              {t("soap.close")}
            </Button>
          </div>
        )}
      </DialogContent>
    </Dialog>
  );
}
